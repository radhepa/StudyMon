/* Compile and run every "what is printed" question and compare the real output
   with the answer the bank claims.

   The bank is a study tool, so a wrong answer teaches the wrong thing. Reading
   the code is not proof; running it is. Snippets are usually the body of main,
   so they are wrapped, and anything needing input or randomness is skipped and
   reported rather than guessed at. */
const fs = require('fs');
const { chromium } = require('./playwright.cjs');
const { window: w } = require('./dump-questions.cjs');
const URL = 'http://127.0.0.1:8780/';

const all = [];
for (const ch of Object.keys(w.QBANK)) for (const q of w.QBANK[ch]) all.push({ ch, ...q });

const HEAD = ['stdio.h', 'stdlib.h', 'string.h', 'ctype.h', 'math.h', 'limits.h', 'stdbool.h', 'stddef.h']
  .map(h => '#include <' + h + '>').join('\n');

/* The bank compiles with -Wall -Wextra -Werror, which is right for a graded
   quest but wrong here: textbook snippets deliberately show an uninitialized
   read or an unused variable, and those must still run so their real output can
   be compared. This copy is generated from the shipped worker at run time with
   the warning flags dropped, so the two cannot drift apart. */
const LAX = 'tools/c-worker-lax.js';
function writeLaxWorker() {
  let src = fs.readFileSync('js/engine/c-worker.js', 'utf8');
  const subs = [
    ["importScripts('../../assets/compiler/shared.js')", "importScripts('../assets/compiler/shared.js')"],
    ["const ROOT='../../assets/compiler/'", "const ROOT='../assets/compiler/'"],
    ["'-Wall','-Wextra','-Werror','-pedantic-errors',", "'-w',"]
  ];
  for (const s of subs) {
    if (!src.includes(s[0])) throw new Error('c-worker.js no longer contains: ' + s[0]);
    src = src.split(s[0]).join(s[1]);
  }
  fs.writeFileSync(LAX, '/* GENERATED by tools/verify-c-answers.cjs from js/engine/c-worker.js.\n'
    + '   Same compiler, warnings not fatal. Do not edit; do not ship. */\n' + src);
}

/* Snippets are usually the body of main, but many define a helper function
   first, sometimes on one line, and sometimes with a global the helper needs.

   A function definition cannot be nested inside main and a global the helper
   reads cannot live inside main either, so everything up to and including the
   last definition is hoisted to file scope and only the trailing statements go
   in main. If a real statement appears before a definition that rule would be
   wrong, so it is detected and the snippet is reported instead of guessed at. */
function findDefs(code) {
  const lines = code.split('\n');
  const spans = [];
  let depth = 0, startLine = -1;
  for (let i = 0; i < lines.length; i++) {
    const t = lines[i].trim();
    if (depth === 0) {
      const isSig = /^[A-Za-z_][\w \t*]*[\s*]\**\w+\s*\([^;]*\)\s*\{/.test(t)
        || (/^[A-Za-z_][\w \t*]*[\s*]\**\w+\s*\([^;]*\)\s*$/.test(t) && (lines[i + 1] || '').trim() === '{');
      const isTypedefStruct = /^typedef\s+struct/.test(t);
      if ((isSig || isTypedefStruct) && !/^(if|for|while|switch|return|else|do)\b/.test(t)) {
        startLine = i;
        for (const ch of lines[i]) { if (ch === '{') depth++; else if (ch === '}') depth--; }
        if (depth === 0 && /}/.test(lines[i])) { spans.push([startLine, i]); startLine = -1; }
        continue;
      }
    } else {
      for (const ch of lines[i]) { if (ch === '{') depth++; else if (ch === '}') depth--; }
      if (depth === 0) { spans.push([startLine, i]); startLine = -1; }
      continue;
    }
    if (depth === 0 && startLine !== -1) {
      for (const ch of lines[i]) { if (ch === '{') depth++; else if (ch === '}') depth--; }
      if (depth === 0) { spans.push([startLine, i]); startLine = -1; }
    }
  }
  return { lines: lines, spans: spans };
}

/* A bare declaration, not a statement that does something. Declarations before
   a helper are usually the global it reads, so they hoist with it. */
function isDeclaration(line) {
  const t = line.trim();
  if (t === '' || t.startsWith('//') || t.startsWith('/*') || t.startsWith('*')) return true;
  if (/^(typedef|struct|union|enum|#)/.test(t)) return true;
  return /^(const\s+)?(unsigned\s+|signed\s+|long\s+|short\s+)*(void|char|int|long|short|float|double|size_t|FILE|[A-Z]\w*)\s*\**\s*\w+\s*(\[[^\]]*\])?\s*(=[^;]*)?;\s*$/.test(t);
}

function split(code) {
  const f = findDefs(code);
  if (!f.spans.length) return { defs: '', stmts: code, trouble: null };
  const last = f.spans[f.spans.length - 1][1];
  const inDef = new Set();
  for (const s of f.spans) for (let i = s[0]; i <= s[1]; i++) inDef.add(i);
  const stray = [];
  for (let i = 0; i <= last; i++) if (!inDef.has(i) && !isDeclaration(f.lines[i])) stray.push(f.lines[i].trim());
  return {
    defs: f.lines.slice(0, last + 1).join('\n'),
    stmts: f.lines.slice(last + 1).join('\n'),
    trouble: stray.length ? 'statement before a function definition: ' + stray[0] : null
  };
}

/* Some snippets use a loop counter the surrounding chapter had already
   declared. Declaring it here keeps the snippet honest without changing it.
   Everything here uses regex literals: escapes inside a constructed RegExp do
   not survive this environment's heredocs. */
function declareLoopVars(defs, stmts) {
  const used = new Set();
  const re = /\bfor\s*\(\s*([A-Za-z_]\w*)\s*=/g;
  let m;
  while ((m = re.exec(stmts)) !== null) used.add(m[1]);
  if (!used.size) return '';
  const TYPE = /^\s*(?:const\s+)?(?:unsigned\s+|signed\s+|long\s+|short\s+)*(?:int|long|short|char|float|double|size_t)\b([^;]*)/;
  const declared = new Set();
  for (const line of (defs + '\n' + stmts).split('\n')) {
    const hit = TYPE.exec(line);
    if (!hit) continue;
    for (const part of (hit[1] || '').split(',')) {
      const name = /([A-Za-z_]\w*)/.exec(part);
      if (name) declared.add(name[1]);
    }
  }
  const need = [...used].filter(n => !declared.has(n));
  return need.length ? 'int ' + need.sort().join(', ') + ';\n' : '';
}

function program(code) {
  if (/\bmain\s*\(/.test(code)) return { src: HEAD + '\n' + code + '\n', trouble: null };
  const parts = split(code);
  const extra = declareLoopVars(parts.defs, parts.stmts);
  return {
    src: HEAD + '\n' + (parts.defs ? parts.defs + '\n\n' : '')
      + 'int main(void)\n{\n' + extra + parts.stmts + '\nreturn 0;\n}\n',
    trouble: parts.trouble
  };
}

const candidates = all.filter(q =>
  q.code && q.k === 'mcq' &&
  /what is printed|what does .* print|what is the output|output of/i.test(q.q));

const skipped = [];
const runnable = candidates.filter(q => {
  const why = function (r) { skipped.push({ id: q.id, reason: r, q: q.q, code: q.code, claimed: q.c[q.a] }); return false; };
  if (/\bscanf\b|\bgets\b/.test(q.code)) return why('reads input');
  if (/\brand\s*\(|\btime\s*\(|\bclock\s*\(/.test(q.code)) return why('nondeterministic');
  if (/\bfopen\b/.test(q.code)) return why('touches files');
  if (/\.\.\./.test(q.code)) return why('snippet is elided');
  return true;
});

console.log(candidates.length + ' print questions, ' + runnable.length + ' runnable, ' + skipped.length + ' skipped');

(async () => {
  writeLaxWorker();
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await (await browser.newContext()).newPage();
  await page.goto(URL);

  const results = [];
  for (let i = 0; i < runnable.length; i++) {
    const q = runnable[i];
    const built = program(q.code);
    const src = built.src;
    const r = await page.evaluate(source => new Promise(resolve => {
      const worker = new Worker('tools/c-worker-lax.js');
      const out = { output: null, diagnostics: '', error: null, exitCode: null };
      const timer = setTimeout(() => { worker.terminate(); resolve(Object.assign(out, { error: 'timeout' })); }, 30000);
      worker.onmessage = e => {
        const m = e.data;
        if (m.type === 'compiled') out.diagnostics = m.diagnostics || '';
        else if (m.type === 'case') { out.output = m.output; out.exitCode = m.exitCode; if (m.error) out.error = m.error; }
        else if (m.type === 'done') { clearTimeout(timer); worker.terminate(); resolve(out); }
        else if (m.type === 'error') { clearTimeout(timer); worker.terminate(); resolve(Object.assign(out, { error: m.message, diagnostics: m.diagnostics || out.diagnostics })); }
      };
      worker.postMessage({ source: source, harness: '', cases: [{ input: '', files: {} }] });
    }), src);
    results.push(Object.assign({ id: q.id, trouble: built.trouble, ch: q.ch, q: q.q, code: q.code, source: src, choices: q.c, a: q.a, claimed: q.c[q.a], why: q.why }, r));
    if ((i + 1) % 25 === 0) console.log('  ran ' + (i + 1) + '/' + runnable.length);
  }
  await browser.close();
  fs.writeFileSync('output/c-answer-verification.json', JSON.stringify({ results: results, skipped: skipped }, null, 1));
  console.log('\nwrote output/c-answer-verification.json (' + results.length + ' results, ' + skipped.length + ' skipped)');
})();
