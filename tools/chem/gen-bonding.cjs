/* Generator for js/data/chem/chem-q-bonding.js (Gym 8 bonding models, Gym 9 Lewis
   structures and molecular shape).

     node tools/chem/gen-bonding.cjs

   The questions themselves live in gen-bonding-m8.cjs and gen-bonding-m9.cjs. Every
   numeric answer and numeric distractor is recomputed here with chk(), which throws if a
   number written into a question disagrees with the arithmetic. The correct choice of
   each mcq is written first in the source and then placed at a balanced, deterministic
   position (A-E) by this script. */
const fs = require('fs');
const path = require('path');

const recs = { 8: [], 9: [] };
let CH = 8;

function chk(label, got, want, tol) {
  const t = tol == null ? 0.051 : tol;
  if (Math.abs(got - want) > t) throw new Error('chk failed: ' + label + ' computed ' + got + ' but text says ' + want);
}
function M(l, t, tag, q, right, wrong, why, hints) {
  if (!Array.isArray(wrong) || wrong.length !== 4) throw new Error('need 4 distractors: ' + q.slice(0, 60));
  recs[CH].push({ k: 'mcq', l, t, tag, q, right, wrong, why, hints });
}
function N(l, t, tag, q, disp, val, why, hints, opts) {
  recs[CH].push({ k: 'num', l, t, tag, q, disp, val, why, hints, opts });
}
const api = { M, N, chk, setCh: n => { CH = n; } };

require('./gen-bonding-m8.cjs')(api);
require('./gen-bonding-m9.cjs')(api);

/* deterministic balanced answer positions: each block of five mcqs uses every slot once */
function rng(seed) { let s = seed >>> 0; return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; }; }
function slots(n, seed) {
  const r = rng(seed), out = [];
  while (out.length < n) {
    const b = [0, 1, 2, 3, 4];
    for (let i = 4; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [b[i], b[j]] = [b[j], b[i]]; }
    out.push(...b);
  }
  return out;
}

const lines = [];
[8, 9].forEach(ch => {
  const list = recs[ch];
  const pos = slots(list.length, ch * 7919);
  let mi = 0;
  list.forEach((r, i) => {
    const id = 'm' + ch + '-a-' + String(i + 1).padStart(3, '0');
    const texts = [r.q, r.why].concat(r.hints);
    if (r.hints.length !== 3) throw new Error(id + ' needs 3 hints');
    let rec;
    if (r.k === 'mcq') {
      const p = pos[mi++];
      const c = r.wrong.slice();
      c.splice(p, 0, r.right);
      if (new Set(c).size !== 5) throw new Error(id + ' duplicate choices');
      texts.push(...c);
      rec = [id, ch, r.l, r.t, r.tag, 'mcq', r.q, c, p, r.why, r.hints];
    } else {
      rec = [id, ch, r.l, r.t, r.tag, 'num', r.q, [r.disp], r.val, r.why, r.hints];
      if (r.opts) rec.push(r.opts);
    }
    texts.forEach(s => {
      if (/[<>]\s*$|->|=>|&[a-z]+;/.test(s)) throw new Error(id + ' suspicious arrow/entity: ' + s.slice(0, 50));
    });
    lines.push(JSON.stringify(rec));
  });
});

const header = `/* GENERATED by tools/chem/gen-bonding.cjs - edit the generator (gen-bonding-m8.cjs,
   gen-bonding-m9.cjs), not this file.

   Periodic Coast question bank: Gym 8 (Models of Chemical Bonding, Silberberg 9.1-9.6,
   lessons 15-16) and Gym 9 (Lewis Structures and Molecular Shape, Silberberg 10.1-10.3,
   lessons 17-19), both on Evening Exam 3 (Nov 19).

   Gym 8: bond types from properties and positions, Lewis dot symbols, ionic bonding and
   formulas, Coulomb's-law lattice-energy rankings, Born-Haber cycles (every step value is
   given in the stem), ionic-solid properties, bond order / length / energy, ΔH°rxn from
   average bond energies (table values given in each stem; Silberberg Table 9.2 values,
   C=O in CO₂ = 799 kJ/mol), comparison with the ΔH°f method (course Table 6.3 values),
   electronegativity (Pauling values given when numbers are needed), bond polarity and
   metallic bonding.
   Gym 9: valence-electron counts, Lewis structures with multiple bonds, resonance and
   average bond order, formal charge and best structures, octet exceptions, VSEPR
   electron-group vs molecular geometry (AX₂ to AX₄E₂), ideal and real bond angles, and
   molecular polarity.

   Every numeric answer and numeric distractor was recomputed by the generator (chk()). */
`;
const out = header + 'chemAddQuestions([\n' + lines.join(',\n') + '\n]);\n';
const dest = path.join(__dirname, '..', '..', 'js', 'data', 'chem', 'chem-q-bonding.js');
fs.writeFileSync(dest, out, 'utf8');
console.log('wrote ' + dest + ': gym 8 ' + recs[8].length + ', gym 9 ' + recs[9].length);
